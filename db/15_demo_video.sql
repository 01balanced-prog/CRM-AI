-- Контроль: ни в одном нетронутом стартовом тексте не осталось «напишите ему»
-- и «[номер демо]». Если админ правил текст сам, строка не считается.
select
  (select count(*) from scripts
    where updated_by is null
      and (body ilike '%напишите ему%' or body ilike '%[номер демо]%')) as stale_0,
  (select count(*) from scripts
    where id in ('00000000-0000-0000-0000-000000000107','00000000-0000-0000-0000-000000000206',
                 '00000000-0000-0000-0000-000000000207','00000000-0000-0000-0000-000000000401',
                 '00000000-0000-0000-0000-000000000403')) as rows_5;
